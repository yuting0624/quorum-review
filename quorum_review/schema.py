"""The JSON contract for findings and verdicts, plus the base model instructions.

The primary and verifier models return the same shapes, defined here. Nothing in
this module may use a construct that only one provider accepts: the constraint is
that every schema below has to feed both Gemini's ``response_schema`` and
Claude's ``output_config.format``.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field
from typing import Any

SEVERITIES = ("critical", "high", "medium", "low")
CATEGORIES = ("security", "correctness", "reliability", "performance", "maintainability")
VERDICTS = ("confirmed", "refuted", "uncertain")

#: Ordering for severity, used when capping verification to the top N findings.
SEVERITY_RANK = {name: index for index, name in enumerate(SEVERITIES)}

#: How many lines a one-click fix may rewrite. Past this it is a refactor, and
#: a refactor nobody read before clicking apply is not an improvement.
MAX_FIX_LINES = 20


@dataclass
class Finding:
    """A single issue reported by the primary model.

    ``finding_id`` is not generated by the model. The ledger derives it
    deterministically from ``file_path`` and a normalised ``code_snippet``, so
    that the identity survives the code moving to a different line.
    """

    file_path: str
    line: int
    category: str
    severity: str
    title: str
    body: str
    code_snippet: str

    #: A whole-line replacement for ``line``..``fix_end_line``, or empty when
    #: the model did not propose one. Only ever rendered as a GitHub suggestion
    #: when it replaces the anchored lines completely: a partial fix that
    #: someone clicks apply on leaves broken code behind.
    fix_replacement: str = ""
    fix_end_line: int = 0

    finding_id: str = ""

    #: Every model that reported this finding **independently**, without having
    #: seen the others' output. Two entries means the models agreed without
    #: being able to influence each other, which is stronger evidence than any
    #: single model's confidence — and it is why an agreed finding needs no
    #: verification pass.
    reported_by: list[str] = field(default_factory=list)

    verdict: str = ""
    verifier_reason: str = ""
    verifier_model: str = ""

    #: Kinds of credential removed from this finding's text before posting, if
    #: any. Named in the comment so a reader knows something was taken out — a
    #: finding that quotes `[redacted]` with no explanation reads like a bug.
    redacted: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @property
    def agreed(self) -> bool:
        return len(self.reported_by) > 1


@dataclass
class Verdict:
    """The verifier's judgement on one finding."""

    verdict: str
    reason: str
    severity: str = ""
    model: str = ""


@dataclass
class PRContext:
    """The pull request under review. Providers see nothing else about GitHub."""

    owner: str
    repo: str
    number: int
    head_sha: str
    base_sha: str
    title: str
    body: str
    diff: str
    changed_files: list[str] = field(default_factory=list)

    #: True when ``diff`` covers only what changed since the last review rather
    #: than the whole pull request. Findings in files absent from an
    #: incremental diff were not looked at, and must not be read as resolved.
    incremental: bool = False

    #: The exclusion patterns actually in force, resolved once when the diff
    #: was selected. Carried here so the models' file tools apply the same set
    #: rather than re-reading ``.quorumignore`` from the checkout.
    #:
    #: Re-reading it would undo the fork protection: the checkout *is* the
    #: branch under review, so the head's copy would govern the tools even
    #: when the base's copy governs the diff. Two reads of the same policy
    #: file, resolved at two different refs, is a gap someone has to notice.
    exclude_patterns: list[str] = field(default_factory=list)


@dataclass
class Skill:
    """Review criteria — the verbatim contents of ``skills/<name>/SKILL.md``."""

    name: str
    content: str


@dataclass
class Discussion:
    """A question asked in the thread under a finding.

    The reviewer answers where the question was asked, with the finding and the
    conversation so far as context. Without this a finding is a verdict handed
    down with no way to argue — and the only remaining moves are to fix it or
    ignore it.
    """

    file_path: str
    line: int
    #: The finding under discussion, when the thread can be matched to one.
    #: A question can also arrive on a thread whose finding has since been
    #: dismissed or resolved, in which case only the code is available.
    title: str = ""
    body: str = ""
    #: ``(author, text)`` oldest first, including the reviewer's own replies.
    transcript: list[tuple[str, str]] = field(default_factory=list)


@dataclass
class ModelUsage:
    """What one model consumed during a review.

    Reported as tokens and calls, never as money: prices differ per model, per
    platform, and per contract, so a dollar figure computed here would be a
    guess presented as a fact. Tokens are what we actually observed.
    """

    calls: int = 0
    input_tokens: int = 0
    output_tokens: int = 0
    cached_input_tokens: int = 0

    def add(
        self,
        input_tokens: int = 0,
        output_tokens: int = 0,
        cached_input_tokens: int = 0,
    ) -> None:
        self.calls += 1
        self.input_tokens += input_tokens
        self.output_tokens += output_tokens
        self.cached_input_tokens += cached_input_tokens


