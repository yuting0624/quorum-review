def for_gemini(schema: Any) -> Any:
    """Strip keys that Gemini's ``response_schema`` does not accept.

    Gemini takes an OpenAPI subset and does not understand
    ``additionalProperties``, while Claude's strict JSON Schema requires
    ``additionalProperties: false``. The schemas above are written for Claude and
    reduced here for Gemini, so there is only one source of truth.
    """
    if isinstance(schema, dict):
        return {
            key: for_gemini(value)
            for key, value in schema.items()
            if key != "additionalProperties"
        }
    if isinstance(schema, list):
        return [for_gemini(item) for item in schema]
    return schema


