_FENCE = re.compile(r"^\s*```(?:json)?\s*|\s*```\s*$", re.MULTILINE)


def parse_json_object(raw: str) -> dict[str, Any]:
    """Extract a JSON object from a model response.

    Even with structured output enabled a model can wrap the payload in a fence
    or prepend a sentence. Three recovery attempts are made; if all fail this
    raises. Callers must treat that as an execution failure rather than as
    "no findings".
    """
    if not raw or not raw.strip():
        raise ValueError("the model returned an empty response")

    # 1. Strip a ```json fence.
    text = _FENCE.sub("", raw).strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # 2. Take the outermost { ... }.
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end > start:
        candidate = text[start : end + 1]
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            # 3. Escape stray backslashes and try once more.
            repaired = re.sub(r'\\(?!["\\/bfnrtu])', r"\\\\", candidate)
            try:
                return json.loads(repaired)
            except json.JSONDecodeError:
                pass

    raise ValueError(f"could not parse as JSON: {text[:200]!r}")


def findings_from_payload(payload: dict[str, Any], model: str) -> list[Finding]:
    """Convert a parsed payload into findings, dropping anything off-schema.

    Malformed entries are discarded silently so that an extra key or an
    out-of-enum value cannot break the stages downstream.
    """
    items = payload.get("findings")
    if not isinstance(items, list):
        return []

    findings: list[Finding] = []
    for item in items:
        if not isinstance(item, dict):
            continue
        try:
            finding = Finding(
                file_path=str(item["file_path"]),
                line=int(item["line"]),
                category=str(item["category"]),
                severity=str(item["severity"]),
                title=str(item["title"]),
                body=str(item["body"]),
                code_snippet=str(item["code_snippet"]),
                fix_replacement=str(item.get("fix_replacement") or ""),
                fix_end_line=int(item.get("fix_end_line") or 0),
                reported_by=[model],
            )
        except (KeyError, TypeError, ValueError):
            continue

        if finding.severity not in SEVERITIES or finding.category not in CATEGORIES:
            continue

        # A fix ending before it starts, or claiming a range far larger than a
        # review comment should rewrite, is discarded rather than trusted.
        if finding.fix_replacement and not (
            finding.line <= finding.fix_end_line <= finding.line + MAX_FIX_LINES
        ):
            finding.fix_replacement = ""
            finding.fix_end_line = 0

        findings.append(finding)

    return findings


def verdict_from_payload(payload: dict[str, Any], model: str) -> Verdict:
    """Convert a parsed payload into a verdict.

    Anything unreadable falls back to ``uncertain``. Demoting a broken response
    to an advisory note is safer than reading it as ``confirmed`` and posting a
    comment nobody stands behind.
    """
    verdict = str(payload.get("verdict", "")).strip().lower()
    if verdict not in VERDICTS:
        verdict = "uncertain"

    severity = str(payload.get("severity", "")).strip().lower()
    if severity not in SEVERITIES:
        severity = ""

    return Verdict(
        verdict=verdict,
        reason=str(payload.get("reason", "")).strip(),
        severity=severity,
        model=model,
    )
